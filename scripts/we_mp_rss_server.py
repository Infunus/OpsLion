"""Run the entire upstream web app plus OpsLion's small workflow API.

Usage is generated by setup-rss.ps1. Never run in the source directory: the
upstream writes relative data/, static/wx_qrcode.png, caches and credentials.
"""
from __future__ import annotations

import argparse
import asyncio
import hmac
import json
import os
from pathlib import Path
import shutil
import sys
import threading


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", required=True, type=Path)
    parser.add_argument("--runtime", required=True, type=Path)
    parser.add_argument("--port", type=int, default=8001)
    args = parser.parse_args()
    source, runtime = args.source.resolve(), args.runtime.resolve()
    if source == runtime or runtime.is_relative_to(source):
        raise ValueError("Runtime must be outside the upstream source directory")
    if not 1 <= args.port <= 65535:
        raise ValueError("Invalid port")
    token = (runtime / "opslion-token.txt").read_text(encoding="utf-8").strip()
    if len(token) < 32:
        raise ValueError("Invalid OpsLion service token")
    # Use a private copy of static files because upstream places QR codes there.
    # Asset hashes avoid overwriting the tree on every service restart.
    import hashlib
    stamp = hashlib.sha256((source / "static/index.html").read_bytes()).hexdigest()
    marker = runtime / "opslion-static.json"
    previous = json.loads(marker.read_text(encoding="utf-8")) if marker.exists() else {}
    if previous != {"source": str(source), "index": stamp}:
        for folder in ("static", "public", "migrations"):
            if (source / folder).is_dir():
                shutil.copytree(source / folder, runtime / folder, dirs_exist_ok=True)
        marker.write_text(json.dumps({"source": str(source), "index": stamp}), encoding="utf-8")
    os.chdir(runtime)
    sys.path.insert(0, str(source))
    sys.dont_write_bytecode = True
    sys.argv = [str(source / "main.py"), "-config", str(runtime / "config.yaml"), "-job", "True"]
    if sys.platform == "win32":
        asyncio.set_event_loop_policy(asyncio.WindowsProactorEventLoopPolicy())

    # Upstream checks GitHub during import and some HTTP calls lack a timeout.
    # Supply a default only; explicit upstream timeouts still take precedence.
    import requests
    original_request = requests.sessions.Session.request

    def bounded_request(session, method, url, **kwargs):
        kwargs.setdefault("timeout", (10, 30))
        return original_request(session, method, url, **kwargs)

    requests.sessions.Session.request = bounded_request
    from core.config import cfg
    if cfg.get("redis.server.enabled", False):
        from tools.redis_server import run_redis_server
        run_redis_server(config_path=str(runtime / "config.yaml"))
    from init_sys import sync_models
    sync_models()
    # Keep migrated upstream users and passwords. Only fresh installations need
    # upstream's normal admin initialization (configured by setup-rss.ps1).
    from core.db import DB
    from core.models.user import User
    with DB.get_session() as session:
        has_users = session.query(User).count() > 0
    if not has_users:
        from init_sys import init_user
        account = json.loads((runtime / "opslion-admin.json").read_text(encoding="utf-8"))
        saved = {key: os.environ.get(key) for key in ("USERNAME", "PASSWORD")}
        try:
            os.environ["USERNAME"], os.environ["PASSWORD"] = account["username"], account["password"]
            init_user(DB)
        finally:
            for key, value in saved.items():
                if value is None:
                    os.environ.pop(key, None)
                else:
                    os.environ[key] = value

    from web import app
    try:
        from core.manual_refresh import get_manual_refresh_tasks
        from we_mp_rss_manual import configure_manual_refresh
        configure_manual_refresh()
        get_manual_refresh_tasks()  # Mark unfinished manual tasks interrupted after restart.
    except ImportError:
        print('RSS 手动采集进度补丁尚未安装，可重新运行 setup-rss.ps1 更新。', flush=True)
    from fastapi import Request, HTTPException
    globals()["Request"] = Request
    from we_mp_rss_adapter import UpstreamAdapter
    adapter = UpstreamAdapter(runtime)

    # Insert before upstream's catch-all Vue route. Keep every native route.
    from fastapi import APIRouter
    router = APIRouter()

    @router.post("/opslion/v1/{operation}")
    async def opslion_call(operation: str, request: Request):
        supplied = request.headers.get("Authorization", "")
        if not hmac.compare_digest(supplied, f"Bearer {token}"):
            raise HTTPException(401)
        if request.headers.get("origin"):
            raise HTTPException(403)  # This API is server-to-server only.
        length = request.headers.get("content-length", "")
        if not length.isdigit() or int(length) > 16384:
            raise HTTPException(413)
        raw = await request.body()
        if len(raw) > 16384:
            raise HTTPException(413)
        try:
            payload = json.loads(raw)
            if not isinstance(payload, dict):
                raise ValueError("请求正文须为 JSON 对象")
            return await asyncio.to_thread(adapter.call, operation, payload)
        except ValueError as error:
            return {"error": True, "message": str(error)}
        except Exception as error:
            # SQL errors may embed article content or credentials. Do not return
            # them to the workbench or browser.
            print(f"OpsLion operation {operation} failed: {type(error).__name__}")
            return {"error": True, "message": "原版 RSS 执行失败，请在完整 RSS 管理界面查看状态"}

    # Local imports above are not in globals used by postponed annotations.
    app.router.routes[0:0] = router.routes
    from driver.auth import start_auth_service
    start_auth_service()
    if cfg.get("cascade.enabled", False) and cfg.get("cascade.node_type") == "child":
        from jobs.cascade_sync import cascade_sync_service
        from jobs.cascade_task_dispatcher import start_child_task_worker
        cascade_sync_service.initialize()
        if cascade_sync_service.sync_enabled:
            threading.Thread(target=lambda: asyncio.run(cascade_sync_service.start_periodic_sync()), daemon=True).start()
            threading.Thread(target=lambda: asyncio.run(start_child_task_worker(cfg.get("cascade.task_poll_interval", 30))), daemon=True).start()
    else:
        from jobs.cascade_task_dispatcher import cascade_schedule_service
        cascade_schedule_service.start()
    if cfg.get("server.enable_job", True):
        from jobs import start_job
        threading.Thread(target=start_job, daemon=True).start()
    if cfg.get("gather.content_auto_check", False):
        from jobs import start_fix_article
        start_fix_article()
    if cfg.get("server.article_stats_refresh_enabled", False):
        from jobs.mps import start_article_stats_refresh
        start_article_stats_refresh()
    import uvicorn
    # One process shares the native queues, browser state and OpsLion job lock.
    asyncio.run(uvicorn.Server(uvicorn.Config(app, host="127.0.0.1", port=args.port, workers=1, log_level="warning")).serve())


if __name__ == "__main__":
    main()
