test("structured imports retain formatting and support full project and template package round trips", async ({ page }) => {
  await mockBridge(page); await ready(page);
  await page.getByRole("button", { name: "模板库", exact: true }).click(); await importTestTemplates(page); await page.getByRole("button", { name: "套用到当前文章", exact: true }).click();
  const article = await page.evaluate(() => structuredClone(window.opTest.layoutEngine.testArticle));
  await page.locator('input[aria-label="导入结构化文稿文件"]').setInputFiles({ name: "example.article.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(article)) });
  await expect(page.locator(".preview-content strong")).toContainText("加粗内容");
  const edited = page.locator('[data-node-id="body-two"] .rich-text-input'); await edited.click(); await edited.press("End"); await edited.press("Control+End"); await page.keyboard.type("文字更新后仍保留加粗。");
  await expect(page.locator(".preview-content strong")).toContainText("加粗内容");
  await saved(page);
  const snapshot = await page.evaluate(async () => {
    const project = (await window.opTest.loadProjects())[0]; const parsed = window.opTest.parseProjectFile({ schema: "wechat-agent-studio/project-v1", project: JSON.parse(JSON.stringify(project)) });
    return { same: window.opTest.renderProject(project) === window.opTest.renderProject(parsed), nodeCount: parsed.layout!.article.nodes.length, originalIds: parsed.layout!.article.nodes.map((node) => node.id), base: parsed.layout!.template.base };
  });
  expect(snapshot.same).toBe(true); expect(snapshot.nodeCount).toBe(article.nodes.length); expect(snapshot.originalIds).toEqual(article.nodes.map((node) => node.id)); expect(snapshot.base).toBeNull();
  await page.getByRole("button", { name: "模板库", exact: true }).click(); await importTestTemplates(page);
  const downloading = page.waitForEvent("download"); await page.getByRole("button", { name: "下载模板包", exact: true }).click();
  const file = await readFile(await (await downloading).path(), "utf8"); const template = JSON.parse(file);
  expect(template.schema).toBe("opslion.layout-template/v1"); expect(template.base).toBeNull(); expect(template.components["bullet-item"]).toBeTruthy();
  template.id = "my-reading"; template.name = "我的阅读模板";
  await page.locator('input[aria-label="导入文章模板包文件"]').setInputFiles({ name: "my-template.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(template)) });
  await expect(page.getByRole("button", { name: "选择我的阅读模板", exact: true })).toBeVisible();
  await page.keyboard.press("Escape"); await page.getByRole("button", { name: "模板库", exact: true }).click(); await importTestTemplates(page);
  await expect(page.getByRole("button", { name: "选择我的阅读模板", exact: true })).toBeVisible();
});

